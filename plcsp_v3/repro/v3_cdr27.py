# -*- coding: utf-8 -*-
"""**27 条 CDR 的全扫**（补 `v3_nhdrl.py` 评测段的标错）。

══ 为什么有这个文件 ══

`v3_nhdrl.py` 的评测段（2026-10-14 加）印的是「**9 条 CDR**」，但那段代码是：

```python
for k in range(N_PA_ACT):                          # 9 条 PA
    ... policy_l=la_rule_policy(0) ...             # LA **钉死在 MINCOST**
print("  9 条 CDR（20 场景均值）：")
```

**9 × 1 ≠ 27。** 那 9 行是「9 条 PA × `MINCOST` 一列」，**不是 CDR 集合**。
原文的 CDR 定义是 *"27 CDRs generated by **pairwise combinations** of PA's and LA's
actions"*（PAGE 16）= **9 × 3**。

⚠️ **后果**：`v3_nhdrl.py` 打出的「最好 CDR 490.5」是 **`MINCOST` 那一列的最小值**，
**不是 27 条的最小值**。

══ 口径：与 `v3_nhdrl.py` 评测段**逐字一致** ══

| 项 | 值 | 出处 |
|---|---|---|
| 实例 | `named(140, 16, seed=0)`（= 训练池的 `i=0`） | `v3_nhdrl.py:367` |
| `build(...)` | 见 `make_spec`，**一字不改** | `v3_nhdrl.py:368-371` |
| 场景 | `100_000 + 13i`，i = 0..19 | `v3_nhdrl.py:455` |
| 入口 | `world.run_gated(..., dt_events=0)` | `v3_nhdrl.py:458` |
| 指标 | 20 场景的 **makespan 均值** ＋ **logistics_cost 均值** | — |

⚠️ **两个目标都要打。** 论文的 CDR 比较是 **HV 意义上的**（Pareto 前沿），不是单看 MS。
`LATEST_IN_TIME` 的式子是「赶得上的取**最晚**到达」⟹ 可能**拿 TC 换 MS**。
只报 MS 会把它误当"最好的 CDR"。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(  # 仓根：本文件在 plcsp_v3/repro/ 下
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

import numpy as np  # noqa: E402

from plcsp_v3.env.shi_instances import N_AGV_SHI, named  # noqa: E402
from plcsp_v3.hrl.rules import (N_AEI2025_RULES,  # noqa: E402
                                PA_RULE_NAMES, apply_pa_rule, la_rule_policy)
from plcsp_v3.q1_flat import SHI_SHOP_LEN, build  # noqa: E402
from plcsp_v3.q1_flat import dims_from_shop_len  # noqa: E402

N_SCEN = int(os.environ.get("C27_SCEN", "20"))
# ⚠️ 复现口径由环境传（同 `v3_nhdrl.py`）：`V3_SCHEME=fig4 V3_SHOPLEN=173 V3_SHI=1`
SCHEME = os.environ.get("V3_SCHEME", "grid")
# ⚠️ **`V3_SHOPLEN`（2026-10-16）**：车间长度 [m]，取代旧的 `V3_SCALE`（无因次倍率）。
SHOPLEN = float(os.environ.get("V3_SHOPLEN", str(SHI_SHOP_LEN)))
SHI = os.environ.get("V3_SHI", "0") == "1"

LA_NAMES = ("MINCOST", "MINU", "LATEST_IN_TIME")


def make_spec():
    """建**一个** world 规格 —— 与 `v3_nhdrl.py:367-371` 逐字同参。"""
    inst = named(140, 16, seed=0)
    spec, _nf = build(seed=0, pm_interval=30, target_failures=4, n_agv=N_AGV_SHI,
                      finite_buffer=True, layout_seed=0, reward_norm="minmax",
                      tau=2.70, sim_overrides={"due_range": 0.6}, inst_obj=inst,
                      layout_scheme=SCHEME, **dims_from_shop_len(SHOPLEN, inst.n_machines), shi2025=SHI)
    return inst, spec


def run_one(spec, k: int, j: int, scs: list[int]) -> tuple[float, float]:
    """一条 `(PA, LA)` 在 `scs` 上的 `(MS 均值, TC 均值)`。**每局新建 world。**"""
    def pol_pa(view, pool, tie_rng=None):
        return apply_pa_rule(k, view, pool, tie_rng)

    pol_l = la_rule_policy(j)
    rows = [spec.world().run_gated(seed_chain=sc, policy_pa=pol_pa,
                                   policy_l=pol_l, dt_events=0) for sc in scs]
    return (float(np.mean([float(r["makespan"]) for r in rows])),
            float(np.mean([float(r["logistics_cost"]) for r in rows])))


def nondominated(pts: list[tuple[float, float]]) -> list[int]:
    """下界方向的非支配集（MS 小、TC 小）。返回下标。"""
    out = []
    for i, (mi, ti) in enumerate(pts):
        if not any((mj <= mi and tj <= ti) and (mj < mi or tj < ti)
                   for j, (mj, tj) in enumerate(pts) if j != i):
            out.append(i)
    return out


def main() -> None:
    inst, spec = make_spec()
    scs = [100_000 + 13 * i for i in range(N_SCEN)]
    print(f"27 条 CDR 全扫 · 实例 Exp(16/140) seed=0 · {N_SCEN} 场景 "
          f"({scs[0]}..{scs[-1]}) · scheme={SCHEME} 车间长={SHOPLEN:.0f}m shi2025={SHI}\n",
          flush=True)

    rows: list[tuple[str, str, float, float]] = []
    for k in range(N_AEI2025_RULES):
        for j in range(3):
            ms, tc = run_one(spec, k, j, scs)
            rows.append((PA_RULE_NAMES[k], LA_NAMES[j], ms, tc))
            print(f"  {PA_RULE_NAMES[k]:<12}{LA_NAMES[j]:<16}{ms:>8.1f}{tc:>10.1f}",
                  flush=True)

    pts = [(r[2], r[3]) for r in rows]
    nd = set(nondominated(pts))

    print("\n  ── 27 条按 MS 升序（前 9）──")
    print(f"  {'':<3}{'PA 规则':<12}{'LA 规则':<16}{'MS':>8}{'TC':>10}  非支配")
    for r, i in enumerate(sorted(range(len(rows)), key=lambda i: pts[i][0])[:9], 1):
        pa, la, ms, tc = rows[i]
        print(f"  {r:>2}. {pa:<12}{la:<16}{ms:>8.1f}{tc:>10.1f}"
              f"  {'★' if i in nd else ''}")

    print("\n  ── 非支配集（MS 与 TC 都小）──")
    for i in sorted(nd, key=lambda i: pts[i][0]):
        pa, la, ms, tc = rows[i]
        print(f"      {pa:<12}{la:<16}{ms:>8.1f}{tc:>10.1f}")

    by_ms = min(range(len(rows)), key=lambda i: pts[i][0])
    by_tc = min(range(len(rows)), key=lambda i: pts[i][1])
    col0 = min((i for i, r in enumerate(rows) if r[1] == "MINCOST"),
               key=lambda i: pts[i][0])
    print(f"\n  MS 最小：{rows[by_ms][2]:.1f}／TC {rows[by_ms][3]:.1f}"
          f"（{rows[by_ms][0]} + {rows[by_ms][1]}）")
    print(f"  TC 最小：{rows[by_tc][2]:.1f}／TC {rows[by_tc][3]:.1f}"
          f"（{rows[by_tc][0]} + {rows[by_tc][1]}）")
    print(f"  `MINCOST` 一列 MS 最小：{rows[col0][2]:.1f}／TC {rows[col0][3]:.1f}"
          f"（{rows[col0][0]} + {rows[col0][1]}）　← `v3_nhdrl.py` 印的就是这个")

    # ── 与"只报 MINCOST 列"的差距，**两个目标分开算** ──
    print("\n  ── 标错造成的低估 ──")
    print(f"      MS：{rows[col0][2]:.1f} → {rows[by_ms][2]:.1f}"
          f"　（{(rows[by_ms][2] - rows[col0][2]) / rows[col0][2]:+.1%}）")
    print(f"      TC：{rows[col0][3]:.1f} → {rows[by_tc][3]:.1f}"
          f"　（{(rows[by_tc][3] - rows[col0][3]) / rows[col0][3]:+.1%}）")

    # ── `LATEST_IN_TIME` 是不是"拿 TC 换 MS" ──
    print("\n  ── `LATEST_IN_TIME` vs `MINCOST`（逐 PA 规则配对）──")
    print(f"  {'PA 规则':<12}{'ΔMS':>10}{'ΔTC':>10}")
    for k in range(N_AEI2025_RULES):
        m0 = next(r for r in rows if r[0] == PA_RULE_NAMES[k] and r[1] == "MINCOST")
        m2 = next(r for r in rows if r[0] == PA_RULE_NAMES[k]
                  and r[1] == "LATEST_IN_TIME")
        print(f"  {m0[0]:<12}{m2[2] - m0[2]:>+10.1f}{m2[3] - m0[3]:>+10.1f}")

    print("\n  ── 每列最好（MS 口径）──")
    for j, la in enumerate(LA_NAMES):
        i = min((i for i, r in enumerate(rows) if r[1] == la), key=lambda i: pts[i][0])
        print(f"  {la:<16}{rows[i][0]:<12}{rows[i][2]:>8.1f}{rows[i][3]:>10.1f}")


if __name__ == "__main__":
    main()
