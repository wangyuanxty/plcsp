def _parse_anchor(spec: str) -> np.ndarray:
    """`"ms,tc;ms,tc"` → `(n, 2)` 数组。空 ⟹ `(0, 2)`。**格式错就显式报错**（不静默丢）。"""
    if not spec.strip():
        return np.zeros((0, 2))
    rows = []
    for grp in spec.split(";"):
        parts = grp.split(",")
        if len(parts) != 2:
            raise ValueError(f"`HV3_BASE` 的一组应是 `MS,TC`，收到 {grp!r}")
        rows.append([float(parts[0]), float(parts[1])])
    return np.asarray(rows, dtype=float)

