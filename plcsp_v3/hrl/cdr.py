# -*- coding: utf-8 -*-
"""**CDR 基线跑器**（步 3 补，2026-10-09）——PA 规则 × LA 规则的组合扫描。

AEI2025 的对比方法里第一条就是 **27 条 CDR**（*"27 CDRs generated by pairwise combinations
of PA's and LA's actions"* = 9 × 3）。我们的动作空间多了 `EDD` 那一块，故自然是 **12 × 3 = 36**。

**两个口径都要能跑**：

- `n_pa_rules=N_AEI2025_RULES`（= 9）⟹ **他们的 27 条**，用于"与已发表基线同规模"的对照；
- `n_pa_rules=N_PA_RULES`（= 12）⟹ **我们的 36 条**，用于"我们自己的动作空间"的对照。

⚠️ **两者不可混为一谈**：36 条里含 `EDD`，而他们的 9 条没有交期规则（见 `hrl/rules.py`）。
论文里报哪个必须写清是哪一个 —— **"27" 与 "36" 是两个不同的基线**。
"""
from __future__ import annotations

from collections.abc import Callable, Iterable

from .rules import (N_AEI2025_RULES, N_PA_RULES, PA_MACHINE_RULES, PA_RULE_NAMES,
                    la_rule_policy, pa_rule_policy)


def cdr_pairs(n_pa_rules: int = N_PA_RULES) -> tuple[tuple[str, str], ...]:
    """`n_pa_rules` 条 PA 规则 × 3 条 LA 规则 → 全部组合 `(pa_name, la_name)`。

    ⚠️ 顺序固定（PA 外层、LA 内层）——**报告里按同一顺序列**，否则两次运行的表对不上。
    """
    if not (1 <= n_pa_rules <= N_PA_RULES):
        raise ValueError(f"n_pa_rules 须在 1..{N_PA_RULES}，实得 {n_pa_rules}")
    return tuple((pa, la) for pa in PA_RULE_NAMES[:n_pa_rules]
                 for la in ("MINCOST", "MINU", "LATEST_IN_TIME"))


def cdr_policies(pa_name: str, la_name: str):
    """一对规则名 → `(policy_pa, policy_l)`，直接喂给 `SimWorld.run_gated`。"""
    return pa_rule_policy(pa_name), la_rule_policy(la_name)


def run_cdr(world, pa_name: str, la_name: str, seed_chain: int = 0,
            tie_seed: int | None = None) -> dict:
    """跑一条 CDR。`world` 由调用方现建（`SimWorld` **一局一用**，不可复用）。

    ⚠️ `tie_seed`（2026-10-20）：平局流与场景流分开。`None` ⟹ 跟随 `seed_chain`
    （逐位等于改动前）。评测精度用：同一场景跑多条平局流。
    """
    pol_pa, pol_l = cdr_policies(pa_name, la_name)
    return world.run_gated(seed_chain=seed_chain, policy_pa=pol_pa, policy_l=pol_l,
                           tie_seed=tie_seed)


def sweep_cdr(world_factory: Callable[[], object], seed_chain: int = 0,
              n_pa_rules: int = N_PA_RULES) -> dict[tuple[str, str], dict]:
    """扫全部组合 → `{(pa, la): metrics}`。

    ⚠️ `world_factory()` **每条都要新建一个世界**——`SimWorld` 持活对象，复用会把上一局的
    状态带进来（`_live_stats` 的账本、`_pa_tie_rng` 的流位置）。
    """
    if n_pa_rules not in (N_AEI2025_RULES, N_PA_RULES):
        # 只挡"写错数"这一类：9 = 他们的，12 = 我们的。别的组合没有对照意义。
        raise ValueError(
            f"n_pa_rules 只接受 {N_AEI2025_RULES}（AEI2025 的 27 条）"
            f" 或 {N_PA_RULES}（我们的 36 条），实得 {n_pa_rules}")
    return {pair: run_cdr(world_factory(), pair[0], pair[1], seed_chain)
            for pair in cdr_pairs(n_pa_rules)}


def objective_bounds(world_factory: Callable[[], object],
                     n_pa_rules: int = N_PA_RULES,
                     seed_chain: int = 0,
                     ) -> tuple[tuple[float, float, float],
                                tuple[float, float, float]]:
    """跑一遍固定规则集 ⟹ 三目标的 `(min, max)`。**min–max 归一化**用。

    照 **Shi et al., *Advanced Engineering Informatics* 65:103195 (2025)** Eq. 51/53 的
    精神：极值取**观测极值**，不引理论下界。

    ⚠️ **极值来自「固定规则集」**，不是全局下界 ⟹ 归一化后的 0/1 是
    "在固定规则能达到的范围内"的两端，**不是物理下/上界**。这条要写进论文。
    ⚠️ 成本 ≈ **0.7 s**（36 条组合，MK01 · 本机实测）⟹ 可在 `build()` 里现算。
    """
    from ..env.reward import objective_vector
    rows = sweep_cdr(world_factory, seed_chain=seed_chain, n_pa_rules=n_pa_rules)
    vals = [objective_vector(m) for m in rows.values()]
    lo = tuple(min(v[i] for v in vals) for i in range(3))
    hi = tuple(max(v[i] for v in vals) for i in range(3))
    return lo, hi            # type: ignore[return-value]


def summarise(rows: dict[tuple[str, str], dict],
              keys: Iterable[str] = ("makespan", "logistics_cost")) -> list[tuple]:
    """`{(pa, la): metrics}` → 按 `keys` 排序的表（每行 `(pa, la, *values)`），**越小越前**。

    默认按 `makespan` 排——CDR 基线在文献里就是按单目标排的（多目标见设计 §11 的裁定）。
    """
    ks = tuple(keys)
    out = [(pa, la) + tuple(float(m[k]) for k in ks) for (pa, la), m in rows.items()]
    return sorted(out, key=lambda r: r[2:])


